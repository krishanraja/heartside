// .github/scripts/header-memo.mjs on a header group shaped like the live one: the memo bar on
// top with the editor's own settings, the v1 offer bar, a Helio announcement and the header.
// The optional --bundle and --artist switches change only those two settings and nothing else.
import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const script = fileURLToPath(new URL('../../.github/scripts/header-memo.mjs', import.meta.url));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hs-memo-'));
const comment = '/*\n * auto-generated by the theme editor\n */';
const group = {
  type: 'header', name: 't:general.header',
  sections: {
    hs2_memo: {type: 'hs2-memo', settings: {deadline: 'Dec 11', offer_label: 'Free US shipping on every order.'}},
    hs_offer: {type: 'hs-announcement', settings: {}},
    announcement: {type: 'announcement-bar', settings: {}},
    header: {type: 'header', settings: {logo_position: 'center'}}
  },
  order: ['hs_offer', 'hs2_memo', 'announcement', 'header']
};
let n = 0;
const file = (g = group) => { const f = path.join(dir, `header-group-${n++}.json`); fs.writeFileSync(f, comment + '\n' + JSON.stringify(g, null, 2) + '\n'); return f; };
const run = (f, ...args) => spawnSync(process.execPath, [script, f, ...args], {encoding: 'utf8'});
const read = f => JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\s*\/\*[\s\S]*?\*\//, ''));

test('without switches it only places the memo bar; the editor settings stay', () => {
  const f = file(); const r = run(f);
  assert.equal(r.status, 0, r.stderr);
  const g = read(f);
  assert.equal(g.order[0], 'hs2_memo'); assert.equal(g.sections.hs_offer, undefined); assert.equal(g.sections.announcement.disabled, true);
  assert.deepEqual(g.sections.hs2_memo.settings, {deadline: 'Dec 11', offer_label: 'Free US shipping on every order.'});
  assert.ok(fs.readFileSync(f, 'utf8').startsWith('/*'), 'the leading comment is kept');
});

test('--bundle on and --artist set exactly those two settings, and run twice changes nothing more', () => {
  const f = file(); let r = run(f, '--bundle', 'on', '--artist', 'artists-touch');
  assert.equal(r.status, 0, r.stderr); assert.match(r.stdout, /bundle saving on/); assert.match(r.stdout, /Artist's touch add-on: artists-touch/);
  const once = fs.readFileSync(f, 'utf8');
  assert.deepEqual(read(f).sections.hs2_memo.settings, {deadline: 'Dec 11', offer_label: 'Free US shipping on every order.', bundle_offer_live: true, artist_touch_product: 'artists-touch'});
  r = run(f, '--bundle', 'on', '--artist', 'artists-touch');
  assert.equal(r.status, 0); assert.equal(fs.readFileSync(f, 'utf8'), once, 'idempotent');
  r = run(f, '--bundle', 'off', '--artist', 'none');
  const s = read(f).sections.hs2_memo.settings;
  assert.equal(s.bundle_offer_live, false); assert.equal('artist_touch_product' in s, false);
});

test('a bad switch value stops before writing', () => {
  for (const args of [['--bundle', 'yes'], ['--artist', 'Bad Handle'], ['--artist', '../x'], ['--artist', '$(id)']]) {
    const f = file(); const before = fs.readFileSync(f, 'utf8');
    const r = run(f, ...args);
    assert.notEqual(r.status, 0, args.join(' ')); assert.equal(fs.readFileSync(f, 'utf8'), before);
  }
});

// audit, 30 Oct: the live memo held "Dec 11", which the countdowns can't read, so every page counted to
// Christmas morning and never said when to order. --deadline writes the one form they read.
test('--deadline sets the last order date in the form the countdowns read, and none clears it', () => {
  const f = file(); let r = run(f, '--deadline', '2026-12-10');
  assert.equal(r.status, 0, r.stderr); assert.match(r.stdout, /last order date for Christmas: 2026-12-10/);
  assert.equal(read(f).sections.hs2_memo.settings.deadline, '2026-12-10');
  r = run(f, '--deadline', 'Dec 10'); assert.notEqual(r.status, 0, 'only YYYY-MM-DD');
  r = run(f, '--deadline', 'none'); assert.equal(r.status, 0, r.stderr);
  assert.equal('deadline' in read(f).sections.hs2_memo.settings, false);
});
