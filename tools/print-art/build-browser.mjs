// Build one browser contract from the same preparation/state source as Node.
// The browser resolves SHA-256 asynchronously; no generation/upload transport exists.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const recipes = JSON.parse(readFileSync(new URL('./recipes-v1.json', import.meta.url), 'utf8'));
const hash = createHash('sha256').update(JSON.stringify(recipes)).digest('hex');
const source = readFileSync(new URL('./artwork-system.mjs', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const body = source.slice(source.indexOf('const clone =')).replace(/^const hash = .*;\r?\n/m, '')
  .replace(/export function /g, 'function ')
  .replace('recipeHash: hash(JSON.stringify(recipes))', 'recipeHash: RECIPE_HASH');
const output = `/* Generated by tools/print-art/build-browser.mjs. Edit the source, not this file. */
(function () {
'use strict';
var recipes = ${JSON.stringify(recipes)};
var RECIPE_HASH = '${hash}';
async function hash(value) {
  var bytes = await window.crypto.subtle.digest('SHA-256', new TextEncoder().encode(value));
  return Array.from(new Uint8Array(bytes), b => b.toString(16).padStart(2, '0')).join('');
}
${body}
window.HSArtworkEngine = {recipes: recipes, recipeHash: RECIPE_HASH,
  prepare: async function(input) { var r = prepare(input); r.key = await r.key; return r; },
  selectTone, newSession, selectRequest, begin, timeout, settle, reconcileFailure, previewState};
}());
`;
const target = new URL('../../shopify/assets/hs-artwork-engine.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Browser artwork contract is stale');
} else writeFileSync(target, output);
