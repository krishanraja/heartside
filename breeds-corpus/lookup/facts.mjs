// Builds shopify/assets/hs-breed-facts.js, the true breed facts the painting wait shows (hs-wait.js).
// Krish, 4 Nov: the fun facts are true; anything invented lives in the dog's own lines.
//   node facts.mjs          writes the theme's copy
//   node facts.mjs --check  exits 1 if it is out of date with the CSVs
// Sources: fun_facts.csv (one fact per row, each with its source_url) for the popular breeds, and one
// general fact per functional_family (below) for every other breed. A named cross gets its parents' facts.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCsv } from './build.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const corpus = path.join(here, '..');
export const THEME_FACTS = path.join(corpus, '..', 'shopify', 'assets', 'hs-breed-facts.js');

// one true, general line per working family, plain enough for anyone
export const FAMILY = {
  'scent hound': 'Scent hounds were bred to follow a trail with their nose, sometimes for hours.',
  'terrier': 'Terrier comes from the Latin terra, earth, because terriers were bred to dig after vermin.',
  'herding dog': 'Herding breeds were bred to move livestock, which is why some try to herd their families.',
  'sighthound': 'Sighthounds hunt by sight and speed, and they are some of the fastest dogs on earth.',
  'retriever': 'Retrievers were bred to bring game back to the hunter without a mark on it.',
  'pointing dog': 'Pointing breeds freeze and aim their nose at a hidden bird, so the hunter knows where to look.',
  'flushing dog': 'Flushing breeds were bred to find birds and send them up into the air for hunters.',
  'water dog': 'Water dogs were bred to work in lakes and rivers, and many have water resistant coats.',
  'water dog / companion': 'Water dogs were bred to work in lakes and rivers, and many have water resistant coats.',
  'gundog': 'Gundogs were bred to work beside hunters in the field all day.',
  'companion': 'Companion breeds were bred for one main job: keeping people company.',
  'working / guardian': 'Guardian breeds were bred to watch over homes, flocks and families.',
  'spitz / primitive': 'Spitz and primitive breeds are among the oldest types of dog on earth.',
  'mixed': 'No two mixed breed dogs are quite alike, so every painting of one is a first.'
};

export function render() {
  const rows = readCsv(path.join(corpus, 'dog_corpus_completed.csv'));
  const facts = readCsv(path.join(corpus, 'fun_facts.csv'));
  const display = readCsv(path.join(corpus, 'us_display_names.csv'));
  const byName = new Map(rows.map((r) => [r.name.toLowerCase(), r.id]));
  const ids = new Set(rows.map((r) => r.id));
  const top = {};
  for (const f of facts) {
    if (!ids.has(f.id)) throw new Error('fun_facts.csv: unknown id ' + f.id);
    if (!/^https:\/\//.test(f.source_url)) throw new Error('fun_facts.csv: no source for ' + f.id);
    if (/!|—|–/.test(f.fact)) throw new Error('fun_facts.csv: exclamation mark or dash in ' + f.id);
    (top[f.id] = top[f.id] || []).push(f.fact);
  }
  const fams = Object.keys(FAMILY);
  const fam = {}, parents = {}, names = {};
  for (const r of rows) {
    const i = fams.indexOf(r.functional_family);
    if (i > -1) fam[r.id] = i;
    if (r.entity_type === 'crossbreed') {
      const p = [r.parent_1, r.parent_2].map((n) => byName.get(String(n).toLowerCase())).filter(Boolean);
      if (p.length) parents[r.id] = p;
    }
    names[r.name.toLowerCase()] = r.id;
  }
  for (const d of display) if (ids.has(d.canonical_id)) names[d.us_display_name.toLowerCase()] = d.canonical_id;
  names['pit bull'] = 'american-staffordshire-terrier';
  names['mixed or not sure'] = 'mixed-breed';
  names['mixed'] = 'mixed-breed';
  const data = { top, family: fams.map((k) => FAMILY[k]), fam, parents, names };
  return `/* Heartside breed facts. GENERATED by breeds-corpus/lookup/facts.mjs from fun_facts.csv and the corpus.
   Do not edit by hand. Every fact is true and sourced (fun_facts.csv); the dog's own lines are the jokes.
   HSBreedFacts.for(idOrName) returns up to three facts: the breed's own, else its parents', else its family's. */
(function (root) {
  'use strict';
  var D = ${JSON.stringify(data)};
  function idOf(x) { x = String(x || '').trim(); if (!x) return ''; if (D.fam[x] != null || D.top[x] || D.parents[x]) return x; return D.names[x.toLowerCase()] || ''; }
  function own(id) { return (D.top[id] || []).slice(); }
  function family(id) { var i = D.fam[id]; return i == null ? [] : [D.family[i]]; }
  function forBreed(x) {
    var id = idOf(x), out = own(id);
    if (!out.length && D.parents[id]) D.parents[id].forEach(function (p) { out = out.concat(own(p).slice(0, 1)); });
    if (!out.length) out = family(id);
    if (!out.length && id === 'mixed-breed') out = [D.family[D.family.length - 1]];
    return out.slice(0, 3);
  }
  root.HSBreedFacts = { for: forBreed, idOf: idOf };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = render();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(THEME_FACTS) ? fs.readFileSync(THEME_FACTS, 'utf8') : '';
    if (now !== text) { console.error('hs-breed-facts.js is out of date: run node facts.mjs'); process.exit(1); }
    console.log('hs-breed-facts.js is current');
  } else { fs.writeFileSync(THEME_FACTS, text); console.log('wrote', path.relative(process.cwd(), THEME_FACTS), text.length, 'bytes'); }
}
